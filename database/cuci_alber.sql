DROP TABLE IF EXISTS `jenis_alats`;
CREATE TABLE `jenis_alats` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `nama` varchar(255) NOT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `jenis_alats_nama_unique` (`nama`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP TABLE IF EXISTS `operators`;
CREATE TABLE `operators` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `nama` varchar(255) NOT NULL,
  `no_hp` varchar(255) DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP TABLE IF EXISTS `unit_alats`;
CREATE TABLE `unit_alats` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `unit_kerja_id` bigint unsigned NOT NULL,
  `jenis_alat_id` bigint unsigned NOT NULL,
  `no_lambung` varchar(255) NOT NULL,
  `kepemilikan` varchar(255) DEFAULT NULL,
  `keterangan` text,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `unit_alats_unit_kerja_id_jenis_alat_id_index` (`unit_kerja_id`,`jenis_alat_id`),
  CONSTRAINT `unit_alats_unit_kerja_id_foreign` FOREIGN KEY (`unit_kerja_id`) REFERENCES `unit_kerjas` (`id`) ON DELETE CASCADE,
  CONSTRAINT `unit_alats_jenis_alat_id_foreign` FOREIGN KEY (`jenis_alat_id`) REFERENCES `jenis_alats` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP TABLE IF EXISTS `unit_operators`;
CREATE TABLE `unit_operators` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `unit_alat_id` bigint unsigned NOT NULL,
  `operator_id` bigint unsigned NOT NULL,
  `grup` enum('A','B','C','D') NOT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `unit_operators_unit_alat_id_grup_unique` (`unit_alat_id`,`grup`),
  KEY `unit_operators_operator_id_foreign` (`operator_id`),
  CONSTRAINT `unit_operators_unit_alat_id_foreign` FOREIGN KEY (`unit_alat_id`) REFERENCES `unit_alats` (`id`) ON DELETE CASCADE,
  CONSTRAINT `unit_operators_operator_id_foreign` FOREIGN KEY (`operator_id`) REFERENCES `operators` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP TABLE IF EXISTS `pengawas`;
CREATE TABLE `pengawas` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `nama` varchar(255) NOT NULL,
  `wilayah` varchar(255) DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP TABLE IF EXISTS `submissions`;
CREATE TABLE `submissions` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `unit_alat_id` bigint unsigned NOT NULL,
  `pengawas_id` bigint unsigned DEFAULT NULL,
  `shift` enum('1','2','3') NOT NULL,
  `operator_nd_id` bigint unsigned DEFAULT NULL,
  `operator_grup_a_id` bigint unsigned DEFAULT NULL,
  `operator_grup_b_id` bigint unsigned DEFAULT NULL,
  `operator_grup_c_id` bigint unsigned DEFAULT NULL,
  `operator_grup_d_id` bigint unsigned DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  `zona_snapshot` varchar(255) DEFAULT NULL,
  `area_kerja_snapshot` varchar(255) DEFAULT NULL,
  `unit_kerja_snapshot` varchar(255) DEFAULT NULL,
  `jenis_alat_snapshot` varchar(255) DEFAULT NULL,
  `no_lambung_snapshot` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `submissions_unit_alat_id_foreign` (`unit_alat_id`),
  KEY `submissions_pengawas_id_foreign` (`pengawas_id`),
  KEY `submissions_operator_nd_id_foreign` (`operator_nd_id`),
  KEY `submissions_operator_grup_a_id_foreign` (`operator_grup_a_id`),
  KEY `submissions_operator_grup_b_id_foreign` (`operator_grup_b_id`),
  KEY `submissions_operator_grup_c_id_foreign` (`operator_grup_c_id`),
  KEY `submissions_operator_grup_d_id_foreign` (`operator_grup_d_id`),
  CONSTRAINT `submissions_unit_alat_id_foreign` FOREIGN KEY (`unit_alat_id`) REFERENCES `unit_alats` (`id`) ON DELETE CASCADE,
  CONSTRAINT `submissions_pengawas_id_foreign` FOREIGN KEY (`pengawas_id`) REFERENCES `pengawas` (`id`) ON DELETE SET NULL,
  CONSTRAINT `submissions_operator_nd_id_foreign` FOREIGN KEY (`operator_nd_id`) REFERENCES `operators` (`id`) ON DELETE SET NULL,
  CONSTRAINT `submissions_operator_grup_a_id_foreign` FOREIGN KEY (`operator_grup_a_id`) REFERENCES `operators` (`id`) ON DELETE SET NULL,
  CONSTRAINT `submissions_operator_grup_b_id_foreign` FOREIGN KEY (`operator_grup_b_id`) REFERENCES `operators` (`id`) ON DELETE SET NULL,
  CONSTRAINT `submissions_operator_grup_c_id_foreign` FOREIGN KEY (`operator_grup_c_id`) REFERENCES `operators` (`id`) ON DELETE SET NULL,
  CONSTRAINT `submissions_operator_grup_d_id_foreign` FOREIGN KEY (`operator_grup_d_id`) REFERENCES `operators` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP TABLE IF EXISTS `submission_photos`;
CREATE TABLE `submission_photos` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `submission_id` bigint unsigned NOT NULL,
  `path` varchar(255) NOT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `submission_photos_submission_id_foreign` (`submission_id`),
  CONSTRAINT `submission_photos_submission_id_foreign` FOREIGN KEY (`submission_id`) REFERENCES `submissions` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

