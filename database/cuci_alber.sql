DROP TABLE IF EXISTS `zonas`;
CREATE TABLE `zonas` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `nama` varchar(255) NOT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `zonas_nama_unique` (`nama`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP TABLE IF EXISTS `area_kerjas`;
CREATE TABLE `area_kerjas` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `zona_id` bigint unsigned NOT NULL,
  `nama` varchar(255) NOT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `area_kerjas_zona_id_nama_unique` (`zona_id`,`nama`),
  CONSTRAINT `area_kerjas_zona_id_foreign` FOREIGN KEY (`zona_id`) REFERENCES `zonas` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP TABLE IF EXISTS `unit_kerjas`;
CREATE TABLE `unit_kerjas` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `area_kerja_id` bigint unsigned NOT NULL,
  `nama` varchar(255) NOT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `unit_kerjas_area_kerja_id_nama_unique` (`area_kerja_id`,`nama`),
  CONSTRAINT `unit_kerjas_area_kerja_id_foreign` FOREIGN KEY (`area_kerja_id`) REFERENCES `area_kerjas` (`id`) ON DELETE CASCADE
